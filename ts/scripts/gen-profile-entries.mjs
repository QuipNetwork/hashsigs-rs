// Generate the per-profile entry points under src/profiles/<profile>/.
//
// Each profile ships its own wasm binary, so each needs its own loader pair
// with a LITERAL relative import of that binary: bundlers resolve the
// `browser` field and the `exports` conditions per file path, and neither can
// follow a computed import. The files are generated rather than hand-written
// because they are identical except for the profile name, and six hand-copied
// loaders drift.
//
// Runs before tsc. The profile list comes from src/profiles/profiles.json,
// which bin/build-wasm.sh emits from bin/packages.sh -- the one place a
// profile is added.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const manifestPath = new URL("src/profiles/profiles.json", root);

let manifest;
try {
  manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
} catch (err) {
  throw new Error(
    `cannot read ${manifestPath.pathname}: run 'bash ../bin/build-wasm.sh ts/src' first ` +
      `(it builds the wasm and writes the profile manifest). Cause: ${err.message}`
  );
}

const { profiles, default: defaultProfile } = manifest;
if (!Array.isArray(profiles) || profiles.length === 0) {
  throw new Error(`${manifestPath.pathname} lists no profiles`);
}
if (!profiles.some((entry) => entry.key === defaultProfile)) {
  throw new Error(
    `${manifestPath.pathname} names default "${defaultProfile}", which is not in its own profile list`
  );
}

const banner = (profile) => `// GENERATED by scripts/gen-profile-entries.mjs -- do not edit.
// Entry point for the "${profile}" SHRINCS profile.
`;

const loaderNode = (profile) => `${banner(profile)}
// Node.js loader. The Node build is wasm-bindgen's \`nodejs\` target: a
// CommonJS module that loads and instantiates the wasm itself on require (no
// async init needed). We reach it via \`createRequire\` so browser bundlers
// never try to resolve the CJS/\`require\` build -- the \`"browser"\` field in
// package.json points them at loader.browser.js instead.
import { createRequire } from "node:module";

type ShrincsWasmModule = typeof import("./nodejs/hashsigs_rs.js");

let cached: ShrincsWasmModule | undefined;

export async function loadShrincsWasm(): Promise<ShrincsWasmModule> {
  if (cached) return cached;
  const require = createRequire(import.meta.url);
  cached = require("./nodejs/hashsigs_rs.js") as ShrincsWasmModule;
  return cached;
}
`;

const loaderBrowser = (profile) => `${banner(profile)}
// Pure-TS signature envelope decoders, re-exported so browser bundles keep
// them: the \`browser\` exports condition maps this profile's entry to THIS
// module, and a value exported only from api.ts would silently be missing.
export { decodeStatefulEnvelope, decodeStatelessSignature } from "../../decode.js";
export type {
  StatefulEnvelopeParts,
  StatefulEnvelopePublicKey,
  StatefulSignatureParts,
  StatelessSignatureParts,
  WotsCSignatureParts,
} from "../../decode.js";

// Browser loader. The browser build is wasm-bindgen's \`web\` target: an ES
// module whose default export instantiates the wasm from bytes. We inline the
// wasm as base64 (generated by scripts/gen-wasm-inline.mjs) and instantiate
// from those bytes so there is no separate \`.wasm\` asset to resolve -- this
// works in any bundler with zero configuration, at the cost of a ~33% larger
// payload. Inlining is also why each profile is its own binary: a bundler
// cannot drop unused profiles out of a base64 string literal.
import init, * as wasm from "./web/hashsigs_rs.js";
import { wasmBase64 } from "./web/inline.js";

type ShrincsWasmModule = typeof wasm;

let cached: Promise<ShrincsWasmModule> | undefined;

export async function loadShrincsWasm(): Promise<ShrincsWasmModule> {
  if (cached) return cached;
  cached = (async () => {
    const bytes = Uint8Array.from(atob(wasmBase64), (c) => c.charCodeAt(0));
    await init({ module_or_path: bytes });
    return wasm;
  })().catch((err) => {
    cached = undefined;
    throw err;
  });
  return cached;
}
`;

const entry = ({ key: profile, name }) => `${banner(profile)}
import { loadShrincsWasm } from "./loader.node.js";
import { makeHashSigs, type HashSigs } from "../../api.js";

// The whole profile-independent surface: key types, the ser/de helpers, and
// \`makeHashSigs\`. Re-exported so one import of this subpath is enough.
export * from "../../api.js";
export { loadShrincsWasm };

/**
 * The npm subpath this module is published under, such as "128s-q18". Note
 * this is the SUBPATH key, not the SHRINCS profile name -- the two differ for
 * the 128s keccak profiles. See \`PROFILE_NAME\` below for the name the binary
 * itself reports.
 */
export const PROFILE = ${JSON.stringify(profile)};

/**
 * The SHRINCS profile name this subpath's binary must report. Declared in
 * \`bin/packages.sh\`, which restates a constant from \`src/profiles/p*.rs\`,
 * so it can drift -- the conformance suite asserts the loaded binary agrees.
 * That assertion is what catches one profile's wasm landing under another's
 * subpath, which nothing else would: all six modules are structurally
 * identical and every type check passes either way.
 */
export const PROFILE_NAME = ${JSON.stringify(name)};

/**
 * Load this profile's wasm once and assemble the noble-style surface on it.
 * Signatures made under this profile do not verify under any other.
 */
export async function loadHashSigs(): Promise<HashSigs> {
  return makeHashSigs(await loadShrincsWasm());
}
`;

for (const profile of profiles) {
  const dir = new URL(`src/profiles/${profile.key}/`, root);
  mkdirSync(dir, { recursive: true });
  writeFileSync(new URL("loader.node.ts", dir), loaderNode(profile.key));
  writeFileSync(new URL("loader.browser.ts", dir), loaderBrowser(profile.key));
  writeFileSync(new URL("index.ts", dir), entry(profile));
}

// The package root re-exports the default profile, so a bare import of
// `@quip.network/hashsigs-wasm` keeps working exactly as before.
writeFileSync(
  new URL("src/index.ts", root),
  `// GENERATED by scripts/gen-profile-entries.mjs -- do not edit.
//
// The package root is the default profile, "${defaultProfile}". Import a
// subpath (for example "@quip.network/hashsigs-wasm/128s-q18") for any other.
// Every profile exports the same names; they differ in what they compute.
export * from "./profiles/${defaultProfile}/index.js";
`
);

console.log(
  `generated ${profiles.length} profile entries (default ${defaultProfile}) into src/profiles/`
);
