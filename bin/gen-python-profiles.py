"""Generate the per-profile Python modules under py/python/hashsigs/profiles/.

Each module binds one compiled extension to the shared surface in
``hashsigs._api``. They are identical except for the profile they name, and six
hand-copied modules drift, so they are generated from the manifest
``bin/build-python.sh`` writes out of ``bin/packages.sh``.
"""
from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PKG = ROOT / "py" / "python" / "hashsigs"
MANIFEST = PKG / "profiles" / "profiles.json"

BANNER = "# GENERATED by bin/gen-python-profiles.py -- do not edit.\n"
LICENSE = "# Copyright (C) 2026 quip.network\n#\n# SPDX-License-Identifier: AGPL-3.0-or-later\n"


def module_source(key: str, name: str, ext_module: str) -> str:
    return f'''{BANNER}{LICENSE}"""The ``{key}`` SHRINCS profile.

Signatures made under this profile do not verify under any other. Pick one
profile per key and keep it.
"""

from .._api import bind
from .._ext import {ext_module}

#: The import key this module is published under, such as ``"128s-q18"``. Note
#: this is the KEY, not the SHRINCS profile name: the two differ for the 128s
#: keccak profiles. See :data:`PROFILE_NAME`.
PROFILE = "{key}"

#: The SHRINCS profile name this module's extension must report. Declared in
#: ``bin/packages.sh``, which restates a constant from ``src/profiles/p*.rs``,
#: so it can drift. ``test_profiles.py`` asserts the loaded extension agrees,
#: which is what catches one profile's extension built under another's name.
PROFILE_NAME = "{name}"

_profile = bind({ext_module})

profile_name = _profile.profile_name
version = _profile.version
max_stateful_signatures = _profile.max_stateful_signatures
sphincs_plus_c = _profile.sphincs_plus_c
shrincs = _profile.shrincs

__all__ = [
    "PROFILE",
    "PROFILE_NAME",
    "max_stateful_signatures",
    "profile_name",
    "shrincs",
    "sphincs_plus_c",
    "version",
]
'''


def main() -> int:
    if not MANIFEST.is_file():
        print(
            f"error: {MANIFEST} is missing; run bin/build-python.sh first "
            "(it builds the extensions and writes the manifest)",
            file=sys.stderr,
        )
        return 1
    manifest = json.loads(MANIFEST.read_text())
    profiles = manifest["profiles"]
    default = manifest["default"]
    if not any(p["key"] == default for p in profiles):
        print(f"error: default {default} is not in the profile list", file=sys.stderr)
        return 1

    for profile in profiles:
        path = PKG / "profiles" / f"{profile['module']}.py"
        path.write_text(module_source(profile["key"], profile["name"], profile["ext"]))

    default_module = [p for p in profiles if p["key"] == default][0]["module"]
    names = "\n".join(f"    {p['module']!r}," for p in profiles)
    (PKG / "profiles" / "__init__.py").write_text(
        f'''{BANNER}{LICENSE}"""One module per SHRINCS profile, each carrying its own compiled extension.

Import the profile you want::

    from hashsigs.profiles import {default_module}

Every module exposes the same names. They differ only in what they compute, and
a signature made under one profile does not verify under any other.
"""

#: Every profile module in this package, by module name, in the order
#: bin/packages.sh lists them.
PROFILES = (
{names}
)

#: The module a bare ``import hashsigs`` binds to. A module name, so it indexes
#: into :data:`PROFILES`; :data:`hashsigs.PROFILE` is the profile KEY, and
#: :data:`hashsigs.PROFILE_NAME` the SHRINCS profile name. The three differ:
#: ``p128s_q18``, ``128s-q18``, and ``shrincs-128s-q18-keccak`` all name one
#: profile.
DEFAULT_MODULE = {default_module!r}
'''
    )

    (PKG / "__init__.py").write_text(
        f'''{BANNER}{LICENSE}"""Hash-based signatures: SHRINCS and SPHINCS+C, backed by hashsigs-rs.

This package carries every SHRINCS profile. The names below are the DEFAULT
profile, ``{default}``::

    from hashsigs import shrincs

Any other profile comes from its own module, and all of them expose the same
names::

    from hashsigs.profiles import p128s_q18

A signature made under one profile does not verify under any other.
"""

from ._api import (
    HashSigsError,
    Profile,
    Shrincs,
    ShrincsKeys,
    ShrincsStateful,
    SphincsPlusC,
    SphincsPlusCKeys,
    SphincsPlusCPublicKey,
    SphincsPlusCSecret,
    StatefulPublicKey,
    shrincs_keys_to_secret_bytes,
)
from ._errors import ERROR_CODES
from ._hashsigs import __version__
from .profiles import DEFAULT_MODULE, PROFILES
from .profiles.{default_module} import (
    PROFILE,
    PROFILE_NAME,
    max_stateful_signatures,
    profile_name,
    shrincs,
    sphincs_plus_c,
    version,
)

__all__ = [
    "DEFAULT_MODULE",
    "ERROR_CODES",
    "HashSigsError",
    "PROFILE",
    "PROFILES",
    "PROFILE_NAME",
    "Profile",
    "Shrincs",
    "ShrincsKeys",
    "ShrincsStateful",
    "SphincsPlusC",
    "SphincsPlusCKeys",
    "SphincsPlusCPublicKey",
    "SphincsPlusCSecret",
    "StatefulPublicKey",
    "__version__",
    "max_stateful_signatures",
    "profile_name",
    "shrincs",
    "shrincs_keys_to_secret_bytes",
    "sphincs_plus_c",
    "version",
]
'''
    )

    ext_imports = "\n".join(
        f"from . import {p['ext']} as {p['ext']}" for p in profiles
    )
    (PKG / "_ext" / "__init__.py").write_text(
        f'''{BANNER}{LICENSE}"""The compiled per-profile extensions.

One shared library per profile, rather than one carrying all six. Importing a
profile maps only that profile's code.

Re-exported by name here so a missing or mismatched build fails at import with
a clear name, rather than at the first call.
"""

{ext_imports}
'''
    )
    print(f"generated {len(profiles)} python profile modules (default {default})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
